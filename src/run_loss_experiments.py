import os
import subprocess
import pandas as pd
import glob
import shutil
import numpy as np
import matplotlib.pyplot as plt
import yaml

def run_experiment(loss_type, experiment_id, epochs=30):
    cmd = [
        r"venv\Scripts\python.exe",
        "src/train.py",
        "--loss_type", loss_type,
        "--experiment_id", experiment_id,
        "--epochs", str(epochs)
    ]
    print(f"==================================================")
    print(f"Starting Experiment: {experiment_id} ({loss_type})")
    print(f"Command: {' '.join(cmd)}")
    print(f"==================================================")
    
    # Run the process and print output in real-time
    process = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in process.stdout:
        print(line, end="")
    process.wait()
    
    if process.returncode != 0:
        raise RuntimeError(f"Experiment {experiment_id} failed with exit code {process.returncode}")

def main():
    base_dir = r"d:\semi-img-restore"
    phase_dir = os.path.join(base_dir, "results", "phase04_losses")
    os.makedirs(phase_dir, exist_ok=True)
    
    experiments = [
        {"loss_type": "L1", "id": "phase04_loss_l1"},
        {"loss_type": "Charbonnier", "id": "phase04_loss_charbonnier"},
        {"loss_type": "Char_SSIM", "id": "phase04_loss_char_ssim"},
        {"loss_type": "Char_SSIM_Grad", "id": "phase04_loss_char_ssim_grad"}
    ]
    
    # 1. Run experiments
    for exp in experiments:
        run_experiment(exp["loss_type"], exp["id"], epochs=30)
        
    # 2. Compile metrics
    summary_data = []
    for exp in experiments:
        metrics_file = os.path.join(phase_dir, exp["id"], "metrics.csv")
        if os.path.exists(metrics_file):
            df = pd.read_csv(metrics_file)
            # Find row with best validation PSNR
            best_idx = df["psnr"].idxmax()
            best_row = df.loc[best_idx]
            summary_data.append({
                "experiment_id": exp["id"],
                "loss_type": exp["loss_type"],
                "best_epoch": int(best_row["epoch"]),
                "val_loss": float(best_row["val_loss"]),
                "psnr": float(best_row["psnr"]),
                "ssim": float(best_row["ssim"]),
                "lpips": float(best_row["lpips"])
            })
            
    summary_df = pd.DataFrame(summary_data)
    summary_df.to_csv(os.path.join(phase_dir, "experiment_matrix.csv"), index=False)
    print("\nExperiment matrix saved to results/phase04_losses/experiment_matrix.csv")
    print(summary_df.to_string(index=False))
    
    # 3. Create visual comparison grid
    print("\nGenerating visual comparison grid...")
    # Find 3 sample images from the first experiment's visuals folder
    visuals_pattern = os.path.join(phase_dir, experiments[0]["id"], "visuals", "*_epoch_*.png")
    all_visuals = glob.glob(visuals_pattern)
    
    # Extract unique filenames of the samples
    sample_names = sorted(list(set([os.path.basename(f).split('_epoch_')[0] for f in all_visuals])))[:3]
    
    if len(sample_names) > 0:
        fig, axes = plt.subplots(len(sample_names), 6, figsize=(24, 4 * len(sample_names)))
        if len(sample_names) == 1:
            axes = np.expand_dims(axes, axis=0)
            
        for row_idx, sample in enumerate(sample_names):
            # Load images
            # Columns: 0: NoisyLR, 1: GT, 2: L1, 3: Charbonnier, 4: Char_SSIM, 5: Char_SSIM_Grad
            # We can find them in the final epoch of validation visuals
            for col_idx, exp in enumerate(experiments):
                exp_vis_dir = os.path.join(phase_dir, exp["id"], "visuals")
                # Find the latest epoch visualization for this sample
                sample_files = sorted(glob.glob(os.path.join(exp_vis_dir, f"{sample}_epoch_*.png")))
                if sample_files:
                    best_file = sample_files[-1] # take final epoch
                    img = plt.imread(best_file)
                    
                    # Split the multi-panel image generated by save_visuals (1 row, 4 cols)
                    # save_visuals saves [NoisyLR, Pred, GT, Residual] as a single image
                    h, w, c = img.shape
                    panel_w = w // 4
                    
                    if col_idx == 0:
                        # Col 0: NoisyLR (first panel)
                        axes[row_idx, 0].imshow(img[:, :panel_w])
                        axes[row_idx, 0].set_title("NoisyLR")
                        axes[row_idx, 0].axis("off")
                        
                        # Col 1: Ground Truth (third panel)
                        axes[row_idx, 1].imshow(img[:, 2*panel_w:3*panel_w])
                        axes[row_idx, 1].set_title("Ground Truth")
                        axes[row_idx, 1].axis("off")
                        
                    # Col 2-5: Predictions (second panel)
                    axes[row_idx, col_idx + 2].imshow(img[:, panel_w:2*panel_w])
                    axes[row_idx, col_idx + 2].set_title(exp["loss_type"])
                    axes[row_idx, col_idx + 2].axis("off")
                    
        plt.tight_layout()
        plt.savefig(os.path.join(phase_dir, "visual_comparison.png"))
        plt.close()
        print("Visual comparison grid saved to results/phase04_losses/visual_comparison.png")
        
    # 4. Save best loss config
    if not summary_df.empty:
        best_exp = summary_df.loc[summary_df["psnr"].idxmax()]
        best_id = best_exp["experiment_id"]
        best_config_src = os.path.join(phase_dir, best_id, "config.yaml")
        best_config_dst = os.path.join(phase_dir, "best_loss_config.yaml")
        if os.path.exists(best_config_src):
            shutil.copy(best_config_src, best_config_dst)
            print(f"Best config copied to results/phase04_losses/best_loss_config.yaml (Best Model: {best_id})")

if __name__ == "__main__":
    main()
